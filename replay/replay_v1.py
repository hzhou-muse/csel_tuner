"""Replay the v1 model builder (csel_tuner/single.py) on recorded data.

    python3 replay/replay_v1.py [--algs binomial,...] [--seeds 3] [--budget 2.0]
                                [--prior] [--tag TAG]
        -> replay/results/v1_runs[_TAG].csv, replay/results/v1_curve[_TAG].csv
    python3 replay/replay_v1.py --report TAG,TAG...  -> replay/results/v1.md

Needs replay/data (README.md). One builder run per (algorithm, seed), from
a blank start, with the recorded layouts as the allowed set and the
recorded sizes as the size grid. A measurement returns one session's median
for that point (sessions picked at random) times exp(N(0, NOISE)), so
repeats differ; its cost is that request's wall time times the
allocation's nodes (billed while the job holds them).

Scored against the ground truth at every recorded layout and size:
|T_pred / T - 1|, median / p90 / max, separately for the layouts the
builder measured (m-axis error only) and the ones it did not (the real
test). "no pen" is the same samples with the non-power-of-two penalty off.
The accuracy-vs-cost curve evaluates the model after each added layout.
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import SHORT, load_gt, results_path  # noqa: E402
from csel_tuner.single import Builder, LayoutModel  # noqa: E402
from common import FIXED, NODES, load_sessions, replay_one  # noqa: E402

NOISE = 0.01


class Replay:
    """measure(n, ppn, [m, ...]) for one algorithm, from the recorded sessions."""
    def __init__(self, sessions, alg, seed):
        self.g, self.alg, self.seed = sessions, alg, seed
        self.count = {}

    def __call__(self, n, ppn, ms):
        out = []
        for m in ms:
            key = (n, ppn, m)
            k = self.count.get(key, 0)
            self.count[key] = k + 1
            out.append(replay_one(self.g, self.seed, self.alg, n, ppn, m, k, NOISE))
        return out


def truth(gt, alg):
    g = gt[gt.alg == alg]
    return {lay: np.log2(d.sort_values("m").t.to_numpy()) for lay, d in g.groupby(["N", "ppn"])}


def errors(model, T, measured):
    """Relative errors per layout class: {'meas': array, 'unmeas': array}."""
    out = {"meas": [], "unmeas": []}
    for lay, y in T.items():
        e = 2 ** np.abs(model.predict(*lay) - y) - 1
        out["meas" if lay in measured else "unmeas"].append(e)
    return {k: np.concatenate(v) if v else np.array([np.nan]) for k, v in out.items()}


def stats(e):
    return np.nanmedian(e), np.nanquantile(e, 0.9), np.nanmax(e)


def run_one(sessions, gt_alg, sizes, layouts, alg, seed, budget, **kw):
    b = Builder(Replay(sessions, alg, seed), layouts, sizes, n_max=max(n for n, _ in layouts),
                ppn_max=max(p for _, p in layouts), seed=seed, **kw)
    b.run(budget_node_h=budget, nodes_billed=NODES)
    meas = set(b.curves)
    row = {"alg": SHORT[alg], "seed": seed, "layouts": len(meas), "meas": b.n_meas,
           "node_h": b.node_h, "stop": b.stop}
    for pen in (True, False):
        e = errors(b.model(penalty=pen), gt_alg, meas)
        tag = "" if pen else " nopen"
        for k in ("meas", "unmeas"):
            md, p90, mx = stats(e[k])
            row.update({f"{k}{tag} med": md, f"{k}{tag} p90": p90, f"{k}{tag} max": mx})
    est = b.estimate()
    row["online med"], row["online p90"] = est if est else (np.nan, np.nan)
    row["random checks"] = sum(c[1] == "random" for c in b.checks)
    curve = []
    for j in range(len(b.history)):
        lays = [h[0] for h in b.history[:j + 1]]
        if len(lays) < 3:
            continue
        sub = {l: b.curves[l] for l in lays}
        md, p90, mx = stats(errors(LayoutModel(sub), gt_alg, set(lays))["unmeas"])
        curve.append({"alg": SHORT[alg], "seed": seed, "layouts": len(lays), "node_h": b.history[j][1] * 1e-6 *
                      NODES / 3600, "meas": b.history[j][2], "unmeas med": md, "unmeas p90": p90,
                      "unmeas max": mx})
    return row, curve, b


def pct(v):
    return "-" if pd.isna(v) else f"{100 * v:.1f}"


def report(tags):
    out = ["# Collective model builder v1: replay on recorded data", "",
           "Generated by `replay/replay_v1.py --report` (method in its docstring and in "
           "`csel_tuner/single.py`). Errors are |T_pred / T - 1| in %, over all 100 sizes of each "
           "layout; *unmeasured* = the layouts the builder did not measure (89 in total). Mean over seeds.", ""]
    loo = results_path("v1_loo.csv")
    if os.path.exists(loo):
        l = pd.read_csv(loo)
        out += ["## Floor of the layout model (leave one layout out, ground-truth curves)", "",
                "Each interior layout (inside the hull of the others of its class) predicted from all "
                "88 others, exact. `rough` = p90 deviation of the ground truth from its own running "
                "median of 3 sizes (single-session noise).", "",
                "| alg | penalty | all med | all p90 | pof2 med | pof2 p90 | non-pof2 med | non-pof2 p90 | rough p90 |",
                "|---|---|---|---|---|---|---|---|---|"]
        for _, r in l.iterrows():
            out.append(f"| {r['alg']} | {'yes' if r['penalty'] else 'no'} | {pct(r['all med'])} | "
                       f"{pct(r['all p90'])} | {pct(r['pof2 med'])} | {pct(r['pof2 p90'])} | "
                       f"{pct(r['non med'])} | {pct(r['non p90'])} | {pct(r['rough p90'])} |")
        out.append("")
    for tag in tags:
        df = pd.read_csv(results_path(f"v1_runs_{tag}.csv"))
        g = df.groupby("alg", sort=False).mean(numeric_only=True)
        stops = df.groupby("alg", sort=False).stop.agg(lambda x: ", ".join(sorted(set(x))))
        out += [f"## Builder runs: {tag}", "",
                "| alg | layouts | measurements | node-h | stop | measured med / p90 | unmeasured med / p90 / max "
                "| same, no penalty | online estimate med / p90 |", "|---|---|---|---|---|---|---|---|---|"]
        for alg, r in g.iterrows():
            out.append(f"| {alg} | {r.layouts:.0f} | {r.meas:.0f} | {r.node_h:.2f} | {stops[alg]} | "
                       f"{pct(r['meas med'])} / {pct(r['meas p90'])} | "
                       f"{pct(r['unmeas med'])} / {pct(r['unmeas p90'])} / {pct(r['unmeas max'])} | "
                       f"{pct(r['unmeas nopen med'])} / {pct(r['unmeas nopen p90'])} | "
                       f"{pct(r.get('online med'))} / {pct(r['online p90'])} |")
        out.append("")
        cv = pd.read_csv(results_path(f"v1_curve_{tag}.csv"))
        cv["bin"] = pd.cut(cv.node_h, [0, 0.1, 0.2, 0.3, 0.5, 0.75, 1.0, 1.5, 2.0, 5.0])
        t = cv.groupby(["alg", "bin"], sort=False, observed=True)[["unmeas med", "unmeas p90"]].mean()
        out += [f"Accuracy vs. cost ({tag}): unmeasured-layout median / p90 error of the model "
                "after each added layout, by node-hours spent.", "",
                "| alg | " + " | ".join(str(b) for b in cv.bin.cat.categories) + " |",
                "|---|" + "---|" * len(cv.bin.cat.categories)]
        for alg in cv.alg.unique():
            cells = []
            for b in cv.bin.cat.categories:
                cells.append(f"{pct(t.loc[(alg, b), 'unmeas med'])} / {pct(t.loc[(alg, b), 'unmeas p90'])}"
                             if (alg, b) in t.index else "")
            out.append(f"| {alg} | " + " | ".join(cells) + " |")
        out.append("")
    open(results_path("v1.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", help="write results/v1.md from the runs with these tags")
    ap.add_argument("--algs", default=",".join(FIXED))
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--budget", type=float, default=2.0, help="node-hours per algorithm")
    ap.add_argument("--prior", action="store_true", help="m sampler with the model's prediction as prior")
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    if a.report:
        return report(a.report.split(","))
    sfx = f"_{a.tag}" if a.tag else ""
    gt = load_gt()
    sessions = load_sessions()
    sizes = np.array(sorted(gt.m.unique()))
    layouts = sorted({(n, p) for n, p in zip(gt.N, gt.ppn)})
    rows, curves = [], []
    for alg in a.algs.split(","):
        T = truth(gt, alg)
        for seed in range(a.seeds):
            row, curve, b = run_one(sessions, T, sizes, layouts, alg, seed, a.budget, use_prior=a.prior)
            rows.append(row)
            curves += curve
            print({k: (round(v, 3) if isinstance(v, float) else v) for k, v in row.items()}, flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(results_path(f"v1_runs{sfx}.csv"), index=False)
    pd.DataFrame(curves).to_csv(results_path(f"v1_curve{sfx}.csv"), index=False)


if __name__ == "__main__":
    main()
